/**
 * Universal lookup helper for translations with fallback to Hindi or English
 */
export function getTranslation(langCode: string, key: TranslationKey): string {
  const langDict = TRANSLATIONS[langCode];
  if (langDict && langDict[key]) {
    return langDict[key]!;
  }
  // Fallback to Hindi
  const hiDict = TRANSLATIONS["hi"];
  if (hiDict && hiDict[key]) {
    return hiDict[key]!;
  }
  // Fallback to English
  const enDict = TRANSLATIONS["en"];
  if (enDict && enDict[key]) {
    return enDict[key]!;
  }
  return key;
}
